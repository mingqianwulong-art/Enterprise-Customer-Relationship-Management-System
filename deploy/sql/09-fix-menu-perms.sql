-- ============================================================
-- CRM 菜单权限补充脚本（P1-2 前端菜单权限过滤配套）
-- 说明：
--   1. init.sql 中 sys_role_menu 仅给 admin(role_id=1) 分配了全部菜单，
--      销售/部门经理无任何菜单权限，导致前端菜单过滤后无可见菜单。
--   2. 客户列表菜单(id=11)的 perms 为 customer:list:list，
--      与 init-perms.sql 按钮权限 customer:customer:list 不一致，统一为后者。
--   3. 补充销售(role_id=3)可见的商机/合同/回款菜单。
--   4. 补充部门经理(role_id=2)可见的全部业务菜单。
-- 适配 MySQL 8.0，可重复执行。
-- ============================================================

USE crm_db;

-- ------------------------------------------------------------
-- 1. 统一客户菜单权限标识（customer:list:list → customer:customer:list）
-- ------------------------------------------------------------
UPDATE sys_menu SET perms = 'customer:customer:list' WHERE id = 11 AND perms = 'customer:list:list';

-- ------------------------------------------------------------
-- 2. 清理旧的菜单分配（保证可重复执行）
-- ------------------------------------------------------------
DELETE FROM sys_role_menu WHERE role_id IN (2, 3) AND menu_id BETWEEN 8 AND 20;

-- ------------------------------------------------------------
-- 3. 部门经理（role_id=2，data_scope=3）：客户+商机+合同+回款+工单+售后+报表
-- ------------------------------------------------------------
INSERT INTO sys_role_menu (role_id, menu_id) VALUES
-- 客户管理（11客户列表 12公海池 13标签）
(2, 11), (2, 12), (2, 13),
-- 商机销售（14商机 15合同 16回款）
(2, 14), (2, 15), (2, 16),
-- 售后服务（17工单 18售后记录）
(2, 17), (2, 18),
-- 数据分析（19数据看板 20自定义报表）
(2, 19), (2, 20);

-- ------------------------------------------------------------
-- 4. 销售（role_id=3，data_scope=1）：客户+商机+合同+回款
-- ------------------------------------------------------------
INSERT INTO sys_role_menu (role_id, menu_id) VALUES
-- 客户管理
(3, 11), (3, 12), (3, 13),
-- 商机销售
(3, 14), (3, 15), (3, 16);

-- ------------------------------------------------------------
-- 5. 验证查询
-- ------------------------------------------------------------
-- 销售拥有的权限标识
SELECT m.perms
FROM sys_role_menu rm
JOIN sys_menu m ON m.id = rm.menu_id
WHERE rm.role_id = 3 AND m.perms IS NOT NULL AND m.perms <> ''
ORDER BY m.perms;
