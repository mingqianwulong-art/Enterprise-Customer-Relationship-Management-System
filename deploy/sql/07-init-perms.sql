-- ------------------------------------------------------------
-- 4. 验证查询
-- ------------------------------------------------------------
-- 管理员拥有的权限标识
SELECT m.perms
FROM sys_role_menu rm
JOIN sys_menu m ON m.id = rm.menu_id
WHERE rm.role_id = 1 AND m.perms IS NOT NULL AND m.perms <> ''
ORDER BY m.perms;

